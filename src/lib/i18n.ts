const TRANSLATIONS: Record<AppLanguage, TranslationDict> = {
  en: EN,
  es: ES,
}

export function t(lang: AppLanguage, key: string, vars?: Record<string, string | number>): string {
  const base = TRANSLATIONS[lang][key] ?? TRANSLATIONS.en[key] ?? key
  if (!vars) return base

  return Object.entries(vars).reduce((acc, [name, value]) => {
    return acc.replace(new RegExp(`\\{${name}\\}`, "g"), String(value))
  }, base)
}

export function assetLabel(lang: AppLanguage, asset: string | null): string {
  if (!asset) return ""
  switch (asset) {
    case "cart":
      return t(lang, "warehouse.cart")
    case "location":
      return t(lang, "warehouse.location")
    case "item":
      return t(lang, "warehouse.item_upc")
    case "tote":
      return t(lang, "warehouse.tote")
    default:
      return asset
  }
}
